#!/usr/bin/env node
// Writes docs/client-emails.md from the templates in netlify/shared/emails,
// rendered with sample data, so James approves exactly what is sent.
// Usage: npm run build:email-docs
const fs = require('fs');
const path = require('path');
const E = require('../netlify/shared/emails');

const out = [];
out.push('# Client journey emails');
out.push('');
out.push('Generated from `netlify/shared/emails/` by `npm run build:email-docs`. Do not edit this file by hand: change the template, then regenerate.');
out.push('');
out.push('`TODO(James): approve wording` for every email below. Sample values are shown in place of real names, links and dates.');
out.push('');
out.push('Every email to a client or a woman is signed by James and ends with a "Report a concern" link. Team emails carry only a reference number and a team-page link.');
out.push('');

function section(code, m) {
  const r = m.build(m.sample);
  out.push('## ' + code + ' — ' + m.name);
  out.push('');
  out.push('- **To:** ' + ({ client: 'the client', woman: 'the woman', team: 'everyone in ADMIN_EMAILS' })[m.audience]);
  if (m.when) out.push('- **When:** ' + m.when);
  out.push('- **Subject:** ' + r.subject);
  out.push('');
  out.push('```text');
  out.push(r.text.trim());
  out.push('```');
  out.push('');
}

for (const code of Object.keys(E)) {
  if (code === 'team') continue;
  const m = E[code];
  if (m.variants) for (const v of Object.keys(m.variants)) section(code + ' (' + v + ')', m.variants[v]);
  else section(code, m);
}
out.push('## Team notifications');
out.push('');
for (const key of Object.keys(E.team)) section('Team', E.team[key]);

const file = path.join(__dirname, '..', 'docs', 'client-emails.md');
fs.writeFileSync(file, out.join('\n'));
console.log('Wrote ' + path.relative(process.cwd(), file));
